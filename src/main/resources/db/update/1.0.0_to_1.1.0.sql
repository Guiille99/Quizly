-- ---------------------------------------------------------------------------
-- Tarjetas inteligentes (mazos y tarjetas con repetición espaciada SM-2)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS mazos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo      VARCHAR(150) NOT NULL,
    descripcion VARCHAR(500),
    usuario_id  BIGINT       NOT NULL,
    tema_id     BIGINT,
    serie_id    BIGINT,
    de_fallos   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP    NOT NULL,
    updated_at  TIMESTAMP    NOT NULL,
    CONSTRAINT fk_mazos_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_mazos_tema
        FOREIGN KEY (tema_id) REFERENCES temas (id) ON DELETE SET NULL,
    CONSTRAINT fk_mazos_serie
        FOREIGN KEY (serie_id) REFERENCES cuestionario_series (id) ON DELETE SET NULL
);

COMMENT ON COLUMN mazos.id IS 'Identificador único del mazo';
COMMENT ON COLUMN mazos.titulo IS 'Título del mazo de tarjetas';
COMMENT ON COLUMN mazos.descripcion IS 'Descripción opcional del mazo';
COMMENT ON COLUMN mazos.usuario_id IS 'Usuario propietario del mazo';
COMMENT ON COLUMN mazos.tema_id IS 'Tema con el que se relaciona el mazo (opcional)';
COMMENT ON COLUMN mazos.serie_id IS 'Serie de cuestionarios de la que se importó el mazo (opcional)';
COMMENT ON COLUMN mazos.de_fallos IS 'Indica si es el mazo automático de repaso de fallos del usuario';
COMMENT ON COLUMN mazos.created_at IS 'Fecha de creación del mazo';
COMMENT ON COLUMN mazos.updated_at IS 'Fecha de última modificación del mazo';

CREATE TABLE IF NOT EXISTS tarjetas (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mazo_id          BIGINT        NOT NULL,
    anverso          VARCHAR(500)  NOT NULL,
    reverso          VARCHAR(1000) NOT NULL,
    pregunta_id      BIGINT,
    repeticiones     INTEGER       NOT NULL DEFAULT 0,
    intervalo_dias   INTEGER       NOT NULL DEFAULT 0,
    facilidad        NUMERIC(4, 2) NOT NULL DEFAULT 2.50,
    proxima_revision TIMESTAMP     NOT NULL,
    ultima_revision  TIMESTAMP,
    created_at       TIMESTAMP     NOT NULL,
    updated_at       TIMESTAMP     NOT NULL,
    CONSTRAINT fk_tarjetas_mazo
        FOREIGN KEY (mazo_id) REFERENCES mazos (id) ON DELETE CASCADE,
    CONSTRAINT fk_tarjetas_pregunta
        FOREIGN KEY (pregunta_id) REFERENCES preguntas (id) ON DELETE SET NULL
);

COMMENT ON COLUMN tarjetas.id IS 'Identificador único de la tarjeta';
COMMENT ON COLUMN tarjetas.mazo_id IS 'Mazo al que pertenece la tarjeta';
COMMENT ON COLUMN tarjetas.anverso IS 'Texto de la cara frontal de la tarjeta (pregunta)';
COMMENT ON COLUMN tarjetas.reverso IS 'Texto de la cara trasera de la tarjeta (respuesta)';
COMMENT ON COLUMN tarjetas.pregunta_id IS 'Pregunta de origen si la tarjeta se importó o se creó por un fallo (opcional)';
COMMENT ON COLUMN tarjetas.repeticiones IS 'Número de repasos correctos consecutivos (SM-2)';
COMMENT ON COLUMN tarjetas.intervalo_dias IS 'Intervalo en días hasta la próxima revisión (SM-2)';
COMMENT ON COLUMN tarjetas.facilidad IS 'Factor de facilidad de la tarjeta, mínimo 1.30 (SM-2)';
COMMENT ON COLUMN tarjetas.proxima_revision IS 'Fecha y hora a partir de la cual la tarjeta está pendiente de repaso';
COMMENT ON COLUMN tarjetas.ultima_revision IS 'Fecha y hora del último repaso de la tarjeta';
COMMENT ON COLUMN tarjetas.created_at IS 'Fecha de creación de la tarjeta';
COMMENT ON COLUMN tarjetas.updated_at IS 'Fecha de última modificación de la tarjeta';

CREATE INDEX IF NOT EXISTS idx_mazos_usuario_id ON mazos (usuario_id);
CREATE INDEX IF NOT EXISTS idx_mazos_tema_id ON mazos (tema_id);
CREATE INDEX IF NOT EXISTS idx_mazos_serie_id ON mazos (serie_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_mazos_usuario_de_fallos ON mazos (usuario_id) WHERE de_fallos;
CREATE UNIQUE INDEX IF NOT EXISTS uk_mazos_usuario_serie ON mazos (usuario_id, serie_id) WHERE serie_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_tarjetas_mazo_proxima_revision ON tarjetas (mazo_id, proxima_revision);
CREATE INDEX IF NOT EXISTS idx_tarjetas_pregunta_id ON tarjetas (pregunta_id);
