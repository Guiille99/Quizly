-- ---------------------------------------------------------------------------
-- Tablas de referencia (sin dependencias)
-- ---------------------------------------------------------------------------

CREATE TABLE tipo_preguntas (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(20)  NOT NULL,
    nombre      VARCHAR(100) NOT NULL,
    CONSTRAINT uk_tipo_preguntas_codigo UNIQUE (codigo)
);

CREATE TABLE dificultades (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo  VARCHAR(10)  NOT NULL,
    nombre  VARCHAR(100) NOT NULL,
    CONSTRAINT uk_dificultades_codigo UNIQUE (codigo)
);

CREATE TABLE intentos_cuestionario_estados (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo  VARCHAR(20)  NOT NULL,
    nombre  VARCHAR(100) NOT NULL,
    CONSTRAINT uk_intentos_cuestionario_estados_codigo UNIQUE (codigo)
);

CREATE TABLE asignaturas (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    slug        VARCHAR(255) NOT NULL,
    created_at  TIMESTAMP    NOT NULL,
    updated_at  TIMESTAMP    NOT NULL,
    CONSTRAINT uk_asignaturas_slug UNIQUE (slug)
);

CREATE TABLE generos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(4)  NOT NULL,
    nombre      VARCHAR(50) NOT NULL,
    CONSTRAINT uk_generos_codigo UNIQUE (codigo)
);

-- ---------------------------------------------------------------------------
-- Tablas con dependencias
-- ---------------------------------------------------------------------------

CREATE TABLE usuarios (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(255) NOT NULL,
    apellidos   VARCHAR(255) NOT NULL,
    username    VARCHAR(50)  NOT NULL,
    email       VARCHAR(100) NOT NULL,
    password    TEXT         NOT NULL,
    rol         VARCHAR(20)  NOT NULL,
    genero_id   BIGINT       NOT NULL,     
    created_at  TIMESTAMP    NOT NULL,
    updated_at  TIMESTAMP    NOT NULL,
    CONSTRAINT uk_usuarios_username UNIQUE (username),
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('ESTUDIANTE', 'ADMIN')),
    CONSTRAINT fk_usuarios_genero
        FOREIGN KEY (genero_id) REFERENCES generos (id)
);

CREATE TABLE temas (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL,
    descripcion   VARCHAR(255),
    slug          VARCHAR(255) NOT NULL,
    orden         INTEGER      NOT NULL,
    created_at    TIMESTAMP    NOT NULL,
    updated_at    TIMESTAMP    NOT NULL,
    asignatura_id BIGINT       NOT NULL,
    CONSTRAINT uk_temas_slug UNIQUE (slug),
    CONSTRAINT fk_temas_asignatura
        FOREIGN KEY (asignatura_id) REFERENCES asignaturas (id)
);

CREATE TABLE cuestionarios (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo         VARCHAR(100) NOT NULL,
    descripcion    VARCHAR(255),
    tiempo_limite  INTEGER,
    slug           VARCHAR(255) NOT NULL,
    created_at     TIMESTAMP    NOT NULL,
    updated_at     TIMESTAMP    NOT NULL,
    tema_id        BIGINT       NOT NULL,
    dificultad_id  BIGINT       NOT NULL,
    CONSTRAINT uk_cuestionarios_slug UNIQUE (slug),
    CONSTRAINT fk_cuestionarios_tema
        FOREIGN KEY (tema_id) REFERENCES temas (id),
    CONSTRAINT fk_cuestionarios_dificultad
        FOREIGN KEY (dificultad_id) REFERENCES dificultades (id)
);

CREATE TABLE preguntas (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enunciado         VARCHAR(255) NOT NULL,
    tipo_pregunta_id  BIGINT       NOT NULL,
    cuestionario_id   BIGINT       NOT NULL,
    CONSTRAINT fk_preguntas_tipo_pregunta
        FOREIGN KEY (tipo_pregunta_id) REFERENCES tipo_preguntas (id),
    CONSTRAINT fk_preguntas_cuestionario
        FOREIGN KEY (cuestionario_id) REFERENCES cuestionarios (id)
);

CREATE TABLE opciones_respuesta (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto       VARCHAR(255) NOT NULL,
    correcta    BOOLEAN      NOT NULL,
    pregunta_id BIGINT       NOT NULL,
    CONSTRAINT fk_opciones_respuesta_pregunta
        FOREIGN KEY (pregunta_id) REFERENCES preguntas (id)
);

CREATE TABLE intentos_cuestionario (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuestionario_id BIGINT    NOT NULL,
    usuario_id      BIGINT    NOT NULL,
    fecha_inicio    TIMESTAMP NOT NULL,
    fecha_fin       TIMESTAMP NOT NULL,
    aciertos        INTEGER   NOT NULL,
    fallos          INTEGER   NOT NULL,
    tiempo_empleado BIGINT    NOT NULL,
    estado_id       BIGINT    NOT NULL,
    CONSTRAINT fk_intentos_cuestionario_cuestionario
        FOREIGN KEY (cuestionario_id) REFERENCES cuestionarios (id),
    CONSTRAINT fk_intentos_cuestionario_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT fk_intentos_cuestionario_estado
        FOREIGN KEY (estado_id) REFERENCES intentos_cuestionario_estados (id)
);

CREATE TABLE respuesta_usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correcta    BOOLEAN NOT NULL,
    intento_id  BIGINT  NOT NULL,
    pregunta_id BIGINT  NOT NULL,
    opcion_id   BIGINT  NOT NULL,
    CONSTRAINT fk_respuesta_usuario_intento
        FOREIGN KEY (intento_id) REFERENCES intentos_cuestionario (id),
    CONSTRAINT fk_respuesta_usuario_pregunta
        FOREIGN KEY (pregunta_id) REFERENCES preguntas (id),
    CONSTRAINT fk_respuesta_usuario_opcion
        FOREIGN KEY (opcion_id) REFERENCES opciones_respuesta (id)
);

